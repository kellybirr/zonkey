    //
    // The classic scaffolder failure: text that looks plausible but does not compile (bad using,
    // mismatched type, syntax error introduced by a template edit). A text diff cannot catch
    // this; only actually compiling the emitted source against the real Zonkey.Data assembly can.

    /// <summary>
    /// The default emit shape (<c>--nullable-refs false</c>) — what a
    /// <c>&lt;Nullable&gt;disable&lt;/Nullable&gt;</c> or net48 consumer actually gets. Held to
    /// the same warnings-as-errors bar as the nullable, `field` and keyword passes: the guarantee
    /// this suite states is "generated code builds clean", and asserting it on only half the
    /// emit matrix is how the last gap survived.
    /// </summary>
    [Fact]
    public void Generated_code_compiles_against_Zonkey_Data()
    {
        CompilationResult result = Compile(
            "GeneratedZoo", NullableContextOptions.Enable, _entitiesDir, warningsAsErrors: true);

        Assert.True(result.Success, "Generated code did not compile:\n" + result.Errors);
    }

    // ---- Layer 3: it round-trips ----------------------------------------------
    //
    // The only layer that proves the *mapping* is right, not just the text. A wrong DbType or a
    // missed IsAutoIncrement compiles cleanly and passes layer 2, then fails here because the
    // insert either throws or the identity value never comes back.

    [Fact]
    public async Task Generated_classes_round_trip_against_the_database()
    {
        CompilationResult compiled = Compile(
            "GeneratedZooRuntime", NullableContextOptions.Disable, _entitiesDir,
            warningsAsErrors: true);
        Assert.True(compiled.Success, "Generated code did not compile:\n" + compiled.Errors);
        Assembly assembly = compiled.Load();

        Type speciesType = assembly.GetType("Zoo.Data.Species")
            ?? throw new InvalidOperationException("Species type missing.");

        await using var cnxn = new SqliteConnection(_conn);
        await cnxn.OpenAsync(TestContext.Current.CancellationToken);

        // Insert through the generated class: proves IsAutoIncrement and DbType are correct,
        // because a wrong key mapping fails here while passing layers 1 and 2.
        object entity = Activator.CreateInstance(speciesType, [true])!;
        speciesType.GetProperty("Name")!.SetValue(entity, "Snow Leopard");
        // SQLite has no native boolean type; the emitter maps INTEGER columns to Int64, so
        // IsEndangered is a `long` property and must be set as one.
        speciesType.GetProperty("IsEndangered")!.SetValue(entity, 1L);

        object adapter = Activator.CreateInstance(
            typeof(DataClassAdapter<>).MakeGenericType(speciesType), [cnxn])!;

        var saveTask = (Task<bool>)adapter.GetType()
            .GetMethod("Save", [speciesType])!
            .Invoke(adapter, [entity])!;

        Assert.True(await saveTask);

        long assignedId = (long)speciesType.GetProperty("SpeciesId")!.GetValue(entity)!;
        Assert.True(assignedId > 0, "Identity value was not selected back after insert.");
    }

    // ---- Nullable ref-types regression guard -----------------------------------
    //
    // The three layers above all run with the default (ProjectProbe-detected) nullable-refs
    // setting, which resolves to false in a temp directory with no .csproj — so they never emit
    // a single "string?" and never exercise CSharpEntityEmitter's "#nullable enable" line at all.
    // A prior task discovered that a file headed "// <auto-generated>" disables the compiler's
    // nullable annotation context, so any "string?" the type mapper bakes in raises CS8669 unless
    // the emitter states "#nullable enable" itself. That fix was proven with a scratch build that
    // no longer exists; nothing here would have caught its removal. These tests explicitly pass
    // --nullable-refs true (bypassing ProjectProbe) to force the path and pin it down for good.

    [Theory]
    [InlineData("Species")]
    [InlineData("Animal")]
    [InlineData("Exhibit")]
    [InlineData("Zookeeper")]
    [InlineData("FeedingSchedule")]
    public void Generated_text_with_nullable_refs_matches_the_golden_file(string className)
    {
        string actual = File.ReadAllText(Path.Combine(_nullableEntitiesDir, $"{className}.g.cs"))
            .ReplaceLineEndings("\n");
        string expectedPath = Path.Combine(
            AppContext.BaseDirectory, "Golden", "Expected", "nullable", $"{className}.g.cs.txt");
        string expected = File.ReadAllText(expectedPath).ReplaceLineEndings("\n");

        Assert.Equal(expected, actual);
    }

    [Fact]
    public void Nullable_context_is_declared_between_the_autogenerated_header_and_the_usings()
    {
        string code = File.ReadAllText(Path.Combine(_nullableEntitiesDir, "Species.g.cs"));

        int headerEnd = code.IndexOf("</auto-generated>", StringComparison.Ordinal);
        int nullableIdx = code.IndexOf("#nullable enable", StringComparison.Ordinal);
        int usingIdx = code.IndexOf("using System;", StringComparison.Ordinal);

        Assert.True(headerEnd >= 0, "auto-generated header missing.");
        Assert.True(nullableIdx > headerEnd, "#nullable enable must come after the auto-generated header.");
        Assert.True(usingIdx > nullableIdx, "#nullable enable must come before the using directives.");
    }

    [Fact]
    public void Nullable_columns_emit_string_and_non_nullable_columns_do_not()
    {
        string species = File.ReadAllText(Path.Combine(_nullableEntitiesDir, "Species.g.cs"));

        // Classification (TEXT, nullable) must be "string?"...
        Assert.Contains("public string? Classification", species);
        // ...while Name (TEXT NOT NULL) must stay a bare "string", never "string?".
        Assert.Contains("public string Name", species);
        Assert.DoesNotContain("public string? Name", species);
    }

