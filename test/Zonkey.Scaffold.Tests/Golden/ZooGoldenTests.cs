    // ---- C# keyword identifiers ------------------------------------------------------
    //
    // NamingEngineTests pins the escaping rule itself; this proves the escaped identifier
    // survives everything downstream of it — the file name, the [Obsolete] message, the
    // pluralized wrapper property, the DataClassAdapter<T> type argument — and still compiles.
    // Uses --naming-style preserve, the mode that bypasses PascalCasing and so is the only way
    // a lower-case reserved word reaches an emitter intact.

    /// <summary>
    /// Two tables, each carrying a different half of the problem:
    /// <c>event</c> is a reserved word (and its columns include <c>class</c>, <c>lock</c>, the
    /// contextual <c>value</c>, and the contextual <c>field</c>), while <c>orders</c> is an
    /// entirely ordinary lower-case table name — the common case under
    /// <c>--naming-style preserve</c>, and the one that raises CS8981.
    /// </summary>
    private const string KeywordDdl = """
        CREATE TABLE "event" (
            "id"    INTEGER PRIMARY KEY AUTOINCREMENT,
            "class" TEXT NOT NULL,
            "lock"  INTEGER NOT NULL,
            "value" TEXT,
            "field" TEXT NOT NULL
        );
        CREATE TABLE "orders" (
            "id"    INTEGER PRIMARY KEY AUTOINCREMENT,
            "total" INTEGER NOT NULL
        );
        """;

    private async Task<string> CreateKeywordDatabase(string name)
    {
        string conn = $"Data Source={Path.Combine(_dir, name + ".db")}";

        await using (var cnxn = new SqliteConnection(conn))
        {
            await cnxn.OpenAsync(TestContext.Current.CancellationToken);
            await using var cmd = cnxn.CreateCommand();
            cmd.CommandText = KeywordDdl;
            await cmd.ExecuteNonQueryAsync(TestContext.Current.CancellationToken);
        }

        SqliteConnection.ClearAllPools();
        return conn;
    }

    private string[] KeywordArgs(string conn, string outDir, string fieldKeyword) =>
    [
        "generate",
        "--provider", "sqlite",
        "--connection", conn,
        // A keyword in a namespace segment is the same defect one level up from the class name,
        // and the namespace reaches both emitters, so it is pinned on the pass that compiles.
        "--namespace", "Zoo.lock.Keywords",
        "--out", outDir,
        // The wrapper's own class name never travelled through the naming layer, so
        // `--wrapper-class lock` used to emit `public partial class lock : DatabaseWrapper`.
        "--wrapper-class", "lock",
        "--naming-style", "preserve",
        "--singularize", "false",
        "--field-keyword", fieldKeyword,
        "--nullable-refs", "true",
        "--config-file", Path.Combine(_dir, "none.json")
    ];

    [Fact]
    public async Task Keyword_named_tables_and_columns_compile()
    {
        string conn = await CreateKeywordDatabase("keywords");
        string outDir = Path.Combine(_dir, "EntitiesKeyword");

        Assert.Equal(0, await Program.Main(KeywordArgs(conn, outDir, "false")));

        string code = File.ReadAllText(Path.Combine(outDir, "@event.g.cs"));

        Assert.Contains("class @event", code);
        Assert.Contains("@class", code);
        Assert.Contains("@lock", code);
        // Contextual keywords: legal as identifiers, so they must stay bare.
        Assert.Contains("public string? value", code);
        Assert.DoesNotContain("@value", code);
        Assert.Contains("public string field", code);
        // The @ is an escape, not part of the name: it must never reach a string literal, and it
        // must not be carried into a derived identifier either ("_@class" is not an identifier).
        Assert.Contains("[DataItem(\"event\")]", code);
        Assert.Contains("[DataField(\"class\"", code);
        Assert.Contains("private string _class", code);
        Assert.DoesNotContain("_@", code);

        // Namespace segments are identifiers too, and both emitters write the namespace.
        Assert.Contains("namespace Zoo.@lock.Keywords;", code);

        string wrapper = File.ReadAllText(Path.Combine(outDir, "@lock.g.cs"));
        Assert.Contains("public partial class @lock : DatabaseWrapper", wrapper);
        Assert.Contains("namespace Zoo.@lock.Keywords;", wrapper);

        // CS8981: an ordinary lower-case table name under preserve is a type name made only of
        // lower-case ASCII, which fails a TreatWarningsAsErrors build unless the generated file
        // says otherwise. An escaped name (@event) is exempt, so it must not carry the pragma.
        string orders = File.ReadAllText(Path.Combine(outDir, "orders.g.cs"));
        Assert.Contains("#pragma warning disable CS8981", orders);
        Assert.DoesNotContain("#pragma warning disable CS8981", code);

        CompilationResult result = Compile(
            "GeneratedKeywords", NullableContextOptions.Enable, outDir, warningsAsErrors: true);

        Assert.True(result.Success, "Keyword-escaped output did not compile:\n" + result.Errors);
    }

    /// <summary>
    /// A column named <c>field</c> under <c>--field-keyword true</c> — the shape
    /// <see cref="Zonkey.Scaffold.Emit.ProjectProbe"/> selects by itself for a net10.0 consumer.
    /// <c>field</c> is a legal identifier, so it is deliberately not escaped; but inside a
    /// property accessor it binds to the synthesized backing field, which makes every
    /// <c>get =&gt; field;</c> in the <em>whole class</em> ambiguous (CS9258), not just the
    /// offending property's. So the fallback has to be class-wide, and this test pins both
    /// halves: the affected class drops to explicit backing fields, and its sibling — same run,
    /// same options, no such column — still uses the keyword.
    /// </summary>
    [Fact]
    public async Task A_column_named_field_falls_back_to_explicit_backing_fields()
    {
        string conn = await CreateKeywordDatabase("fieldcolumn");
        string outDir = Path.Combine(_dir, "EntitiesFieldColumn");

        Assert.Equal(0, await Program.Main(KeywordArgs(conn, outDir, "true")));

        string code = File.ReadAllText(Path.Combine(outDir, "@event.g.cs"));
        Assert.Contains("private string _field = null!;", code);
        Assert.DoesNotContain("get => field;", code);

        string orders = File.ReadAllText(Path.Combine(outDir, "orders.g.cs"));
        Assert.Contains("get => field;", orders);
        Assert.DoesNotContain("private long _id", orders);

        CompilationResult result = Compile(
            "GeneratedFieldColumn", NullableContextOptions.Enable, outDir,
            warningsAsErrors: true, languageVersion: LanguageVersion.Preview);

        Assert.True(result.Success,
            "Output for a table with a column named `field` did not compile:\n" + result.Errors);
    }

    // ---- shared compile helper --------------------------------------------------

    private readonly record struct CompilationResult(bool Success, string Errors, byte[] AssemblyBytes)
    {
        public Assembly Load() => Assembly.Load(AssemblyBytes);
    }

    /// <summary>
    /// The only warnings exempted from the blanket escalation, and both are properties of the
    /// *test host's* reference set rather than of the generated code:
    /// CS1701/CS1702 are assembly-reference version unification notices, raised because this
    /// compilation is handed every assembly the xunit host happens to have loaded. The generated
    /// code cannot cause or avoid them. Every diagnostic that a generated file can actually
    /// provoke — the whole CS86xx nullable family included — stays an error.
    /// </summary>
    private static readonly IReadOnlyDictionary<string, ReportDiagnostic> ToleratedWarnings =
        new Dictionary<string, ReportDiagnostic>
        {
            ["CS1701"] = ReportDiagnostic.Suppress,
            ["CS1702"] = ReportDiagnostic.Suppress,
        };

    /// <summary>
    /// Compiles every generated *.g.cs file in <paramref name="sourceDir"/> against the current
    /// AppDomain's assemblies (which already includes Zonkey.Data via the test project's
    /// ProjectReference). Shared by layer 2 (checks success/errors only), layer 3 (also loads the
    /// resulting assembly to exercise it at runtime), and every regression guard, so the Roslyn
    /// compilation logic exists exactly once regardless of which variant of the generated output
    /// is under test.
    /// </summary>
    /// <param name="warningsAsErrors">
    /// Promotes every warning to an error, i.e. compiles the way a consumer project with
    /// <c>TreatWarningsAsErrors</c> would. Deliberately general rather than an allow-list of
    /// diagnostic codes: an allow-list only ever guards the bug that was known when it was
    /// written. See <see cref="ToleratedWarnings"/> for the two carve-outs and why they are safe.
    /// <para>
    /// Required rather than defaulted, and true at all six call sites. It used to default to
    /// false, and two passes — including the default emit shape — silently opted out of the
    /// guarantee the other four asserted. A required parameter makes a future call site state its
    /// choice instead of inheriting the weaker one by omission.
    /// </para>
    /// </param>
    /// <param name="languageVersion">
    /// C# 14 (<see cref="LanguageVersion.Preview"/>) is required for the `field` keyword path;
    /// everything else compiles under the default.
    /// </param>
    private CompilationResult Compile(
        string assemblyName,
        NullableContextOptions nullableContext,
        string sourceDir,
        bool warningsAsErrors,
        LanguageVersion languageVersion = LanguageVersion.Latest)
    {
        var parseOptions = new CSharpParseOptions(languageVersion);

        var trees = Directory
            .EnumerateFiles(sourceDir, "*.g.cs")
            .OrderBy(f => f, StringComparer.Ordinal)
            .Select(f => CSharpSyntaxTree.ParseText(File.ReadAllText(f), parseOptions, path: f))
            .ToList();

        // AppDomain.CurrentDomain.GetAssemblies() only reflects assemblies some earlier code path
        // has already touched. Running this whole test class together happens to touch
        // Zonkey.Data early (the round-trip test references DataClassAdapter<> directly), but
        // running this test filtered/in isolation does not — nothing in this method's own body
        // otherwise names a Zonkey.Data type, so the snapshot below would omit Zonkey.Data.dll
        // entirely and every generated file would fail with unrelated "DataField"/"SetFieldValue"
        // errors instead of the diagnostic the test actually cares about. Resolve
        // Zonkey.Data's location directly from a known type rather than trusting it is already
        // loaded, so this helper is correct regardless of what else has (or hasn't) run first.
        Assembly zonkeyData = typeof(Zonkey.ObjectModel.DataClass).Assembly;

        var references = AppDomain.CurrentDomain
            .GetAssemblies()
            .Append(zonkeyData)
            .Where(a => !a.IsDynamic && !string.IsNullOrEmpty(a.Location))
            .Distinct()
            .Select(a => MetadataReference.CreateFromFile(a.Location))
            .Cast<MetadataReference>()
            .ToList();

        var options = new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary,
            nullableContextOptions: nullableContext);

        if (warningsAsErrors)
        {
            options = options
                .WithGeneralDiagnosticOption(ReportDiagnostic.Error)
                .WithSpecificDiagnosticOptions(ToleratedWarnings);
        }

        var compilation = CSharpCompilation.Create(assemblyName, trees, references, options);

        using var ms = new MemoryStream();
        EmitResult result = compilation.Emit(ms);

        string errors = string.Join("\n", result.Diagnostics
            .Where(d => d.Severity == DiagnosticSeverity.Error)
            .Select(d => d.ToString()));

        return new CompilationResult(result.Success, errors, ms.ToArray());
    }
