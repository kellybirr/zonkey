using Zonkey.Scaffold;

namespace Zonkey.Scaffold.Tests.Golden;

// Program.Main's "generate" path reports through the default writer, which is Console.Out when
// invoked the way CliSmokeTests and this class invoke it (no DI override) — so this class joins
// the same "ScaffoldConsole" collection for the same reason CliSmokeTests does. See the doc
// comment on ScaffoldConsoleCollection in Cli/CommandTests.cs.
[Collection("ScaffoldConsole")]
public class ZooGoldenTests : IAsyncLifetime
{
    private string _dir = "";
    private string _dbPath = "";
    private string _conn = "";
    private string _entitiesDir = "";
    private string _nullableEntitiesDir = "";
    private string _fieldEntitiesDir = "";

    public async ValueTask InitializeAsync()
    {
        _dir = Directory.CreateTempSubdirectory("zgolden").FullName;
        _dbPath = Path.Combine(_dir, "zoo.db");
        _conn = $"Data Source={_dbPath}";
        _entitiesDir = Path.Combine(_dir, "Entities");
        _nullableEntitiesDir = Path.Combine(_dir, "EntitiesNullable");
        _fieldEntitiesDir = Path.Combine(_dir, "EntitiesField");

        await using (var cnxn = new SqliteConnection(_conn))
        {
            await cnxn.OpenAsync();
            await using var cmd = cnxn.CreateCommand();
            cmd.CommandText = File.ReadAllText(
                Path.Combine(AppContext.BaseDirectory, "Golden", "zoo-sqlite.sql"));
            await cmd.ExecuteNonQueryAsync();
        }

        int exit = await Program.Main([
            "generate",
            "--provider", "sqlite",
            "--connection", _conn,
            "--namespace", "Zoo.Data",
            "--out", _entitiesDir,
            "--wrapper-class", "ZooDatabase",
            "--field-keyword", "false",
            "--config-file", Path.Combine(_dir, "none.json")
        ]);

        Assert.Equal(0, exit);

        // Second generation pass, explicitly with --nullable-refs true. The temp directory this
        // test generates into has no .csproj, so ProjectProbe finds nothing and Emit:NullableRefs
        // resolves to "auto" -> false — the default run above never emits "#nullable enable" or a
        // single "string?". Passing --nullable-refs true bypasses ProjectProbe's detection
        // entirely, which is required to exercise the CS8669 guard described on
        // CSharpEntityEmitter.Emit: a file starting with "// <auto-generated>" disables the
        // compiler's nullable annotation context, so "#nullable enable" must be emitted whenever
        // the type mapper bakes a "?" into a ClrType, or every nullable reference property raises
        // CS8669 under TreatWarningsAsErrors.
        int nullableExit = await Program.Main([
            "generate",
            "--provider", "sqlite",
            "--connection", _conn,
            "--namespace", "Zoo.Data",
            "--out", _nullableEntitiesDir,
            "--wrapper-class", "ZooDatabase",
            "--field-keyword", "false",
            "--nullable-refs", "true",
            "--config-file", Path.Combine(_dir, "none.json")
        ]);

        Assert.Equal(0, nullableExit);

        // Third pass: the shape a modern consumer actually gets. ProjectProbe selects the `field`
        // keyword automatically for a net10.0 project and nullable refs automatically for
        // <Nullable>enable</Nullable>, so `field` + nullable together is the default emit shape
        // for any project created since .NET 10 — and it was the one combination with no compile
        // coverage at all. Both are forced explicitly here because the temp output directory has
        // no .csproj for ProjectProbe to read.
        int fieldExit = await Program.Main([
            "generate",
            "--provider", "sqlite",
            "--connection", _conn,
            "--namespace", "Zoo.Data",
            "--out", _fieldEntitiesDir,
            "--wrapper-class", "ZooDatabase",
            "--field-keyword", "true",
            "--nullable-refs", "true",
            "--config-file", Path.Combine(_dir, "none.json")
        ]);

        Assert.Equal(0, fieldExit);

        // Pool eviction happens on Dispose, but SQLite keeps the file mapped until pools are
        // cleared explicitly; do it once up front so a later test in this class can safely
        // reopen the same file without file-lock contention on Windows.
        SqliteConnection.ClearAllPools();
    }

    public ValueTask DisposeAsync()
    {
        SqliteConnection.ClearAllPools();
        Directory.Delete(_dir, recursive: true);
        return ValueTask.CompletedTask;
    }

    // ---- Layer 1: golden text -------------------------------------------------
    //
    // Catches drift in the generator's text output and makes intentional changes reviewable as
    // diffs. This layer cannot catch a scaffolder that emits code which fails to compile, or
    // code that compiles but maps the wrong DbType/IsAutoIncrement — that is what layers 2 and 3
    // are for.

    [Theory]
    [InlineData("Species")]
    [InlineData("Animal")]
    [InlineData("Exhibit")]
    [InlineData("Zookeeper")]
    [InlineData("FeedingSchedule")]
    public void Generated_text_matches_the_golden_file(string className)
    {
        string actual = File.ReadAllText(Path.Combine(_entitiesDir, $"{className}.g.cs"))
            .ReplaceLineEndings("\n");
        string expectedPath = Path.Combine(
            AppContext.BaseDirectory, "Golden", "Expected", $"{className}.g.cs.txt");

        // To refresh after an intentional generator change:
        //   copy the generated file over the .txt and review the diff by hand before accepting.
        string expected = File.ReadAllText(expectedPath).ReplaceLineEndings("\n");

        Assert.Equal(expected, actual);
    }

