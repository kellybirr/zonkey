using Xunit;
using Zonkey.Scaffold.Diagnostics;
using Zonkey.Scaffold.Emit;

public class CSharpEntityEmitterTests
{
    private static EntityModel Order() => new()
    {
        ClassName = "Order",
        TableName = "orders",
        Properties =
        [
            new PropertyModel { Name = "Id", ColumnName = "id", DbType = "Int32",
                                ClrType = "int", IsKey = true, IsIdentity = true },
            new PropertyModel { Name = "Name", ColumnName = "name", DbType = "String",
                                ClrType = "string", Length = 100 },
            new PropertyModel { Name = "Notes", ColumnName = "notes", DbType = "String",
                                ClrType = "string?", IsNullable = true, Length = 500 },
        ]
    };

    private static EntityEmitOptions Opts(bool fieldKeyword = true) => new()
    {
        Namespace = "MyApp.Data",
        PartialClasses = true,
        VirtualProperties = false,
        FieldKeyword = fieldKeyword,
        NullableRefs = true
    };

    private static string Emit(EntityModel? m = null, EntityEmitOptions? o = null)
        => new CSharpEntityEmitter().Emit(m ?? Order(), o ?? Opts());

    [Fact]
    public void Starts_with_the_auto_generated_header()
        => Assert.StartsWith("// <auto-generated>", Emit());

    [Fact]
    public void Header_carries_no_timestamp_or_version()
    {
        string code = Emit();
        Assert.DoesNotContain("2026", code);
        Assert.DoesNotContain("7.0.0", code);
    }

