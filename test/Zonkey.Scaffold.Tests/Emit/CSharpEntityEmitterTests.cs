    public void Obsolete_attribute_is_error_level()
        => Assert.Matches(@"\[Obsolete\("".*"", true\)\]", Emit());

    [Fact]
    public void Field_keyword_mode_emits_no_backing_fields()
    {
        string code = Emit(null, Opts(fieldKeyword: true));
        Assert.Contains("public int Id { get => field; set => SetFieldValue(ref field, value); }", code);
        Assert.DoesNotContain("private int _id;", code);
    }

    [Fact]
    public void Backing_field_mode_emits_private_fields()
    {
        string code = Emit(null, Opts(fieldKeyword: false));
        Assert.Contains("private int _id;", code);
        Assert.Contains("get => _id;", code);
        Assert.Contains("set => SetFieldValue(ref _id, value);", code);
    }

    [Fact]
    public void PrivateFieldsAtTop_groups_fields_before_properties()
    {
        var o = Opts(fieldKeyword: false);
        o.PrivateFieldsAtTop = true;
        string code = Emit(null, o);

        int firstField = code.IndexOf("private int _id;", StringComparison.Ordinal);
        int firstProperty = code.IndexOf("public int Id", StringComparison.Ordinal);
        Assert.True(firstField < firstProperty);
    }

    [Fact]
    public void Emits_key_and_identity_flags()
        => Assert.Contains(
            "[DataField(\"id\", DbType.Int32, false, IsKeyField = true, IsAutoIncrement = true)]",
            Emit());

    [Fact]
    public void Emits_length_for_strings()
        => Assert.Contains("Length = 100", Emit());

    // Regression coverage for the SQL Server NTEXT/TEXT/IMAGE length bug: SqlServerSchemaReader
    // must report MaxLength = null for those three legacy LOB types (see
    // SqlServerSchemaReaderTests.Legacy_lob_types_report_null_length_not_their_pointer_stub_size),
    // and ScaffoldPipeline.cs:304 copies ColumnInfo.MaxLength straight into PropertyModel.Length
    // with no further logic -- so a null here is the one property this emitter needs to get right
    // for the whole chain to actually omit a bogus size from the generated [DataField]. Before the
    // reader fix, an NTEXT column's MaxLength (and therefore Length here) came out as 8 -- the
    // in-row LOB pointer's 16-byte stub halved by the Unicode-length correction -- which this test
    // would have caught as "Length = 8" appearing below.
    [Fact]
    public void Omits_length_entirely_when_null()
    {
        var m = Order();
        m.Properties.Add(new PropertyModel { Name = "Description", ColumnName = "description",
                                              DbType = "String", ClrType = "string?",
                                              IsNullable = true, Length = null });

        string code = Emit(m);
        // The exact-string assertion (attribute closes right after the nullability flag) is the
        // real proof: if Length were emitted for a null value, this line simply would not match.
        Assert.Contains("[DataField(\"description\", DbType.String, true)]", code);
    }

    [Fact]
    public void Emits_nullability_as_the_third_positional_argument()
    {
        string code = Emit();
        Assert.Contains("[DataField(\"notes\", DbType.String, true", code);
        Assert.Contains("[DataField(\"name\", DbType.String, false", code);
    }

