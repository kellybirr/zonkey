    [Fact]
    public void Non_partial_when_disabled()
    {
        var o = Opts();
        o.PartialClasses = false;
        Assert.Contains("public class Order : DataClass", Emit(null, o));
    }

    [Fact]
    public void Emits_obsolete_parameterless_constructor()
    {
        string code = Emit();
        Assert.Contains("public Order(bool addingNew) : base(addingNew)", code);
        Assert.Contains("[Obsolete(", code);
        Assert.Contains("public Order() : this(false) { }", code);
    }

