    // ---- CS8618/CS9264: non-nullable storage the constructor never assigns ----------
    //
    // Under "#nullable enable" a non-nullable reference-typed backing field that no constructor
    // writes is a compiler warning (an error in any project with TreatWarningsAsErrors), which
    // made the tool's normal output dirty-to-broken in every modern consumer project. The value
    // really is supplied out of band by the materializer, so "= null!" states the truth; the fix
    // must stay narrow, which is what the negative cases below pin.

    [Fact]
    public void Non_nullable_reference_backing_field_is_null_forgiving()
        => Assert.Contains("private string _name = null!;", Emit(null, Opts(fieldKeyword: false)));

    [Fact]
    public void Nullable_reference_backing_field_is_not_null_forgiving()
    {
        string code = Emit(null, Opts(fieldKeyword: false));
        Assert.Contains("private string? _notes;", code);
        Assert.DoesNotContain("private string? _notes = null!;", code);
    }

    [Fact]
    public void Value_typed_backing_field_is_not_null_forgiving()
    {
        string code = Emit(null, Opts(fieldKeyword: false));
        Assert.Contains("private int _id;", code);
        Assert.DoesNotContain("_id = null!", code);
    }

    [Fact]
    public void Nothing_is_null_forgiving_when_nullable_refs_are_off()
    {
        var o = Opts(fieldKeyword: false);
        o.NullableRefs = false;
        Assert.DoesNotContain("null!", Emit(null, o));
    }

    [Fact]
    public void Field_keyword_property_carries_the_null_forgiving_initializer()
    {
        string code = Emit(null, Opts(fieldKeyword: true));
        Assert.Contains(
            "public string Name { get => field; set => SetFieldValue(ref field, value); } = null!;", code);
        Assert.Contains(
            "public string? Notes { get => field; set => SetFieldValue(ref field, value); }\n", code);
    }

    [Fact]
    public void PrivateFieldsAtTop_block_is_null_forgiving_too()
    {
        var o = Opts(fieldKeyword: false);
        o.PrivateFieldsAtTop = true;
        Assert.Contains("private string _name = null!;", Emit(null, o));
    }

