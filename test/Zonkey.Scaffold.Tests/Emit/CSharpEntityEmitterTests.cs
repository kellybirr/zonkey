    // ---- CS9258: a property named `field` under --field-keyword ----------------------
    //
    // `field` is a legal identifier and so is deliberately not escaped by NamingEngine. But
    // inside a property accessor it binds to the synthesized backing field, so a member named
    // `field` makes every `get => field;` in the whole class ambiguous — the diagnostic is
    // class-wide, which is why the fallback has to be too.

    private static EntityModel WithFieldColumn()
    {
        var m = Order();
        m.Properties.Add(new PropertyModel
        {
            Name = "field", ColumnName = "field", DbType = "String", ClrType = "string"
        });
        return m;
    }

    [Fact]
    public void A_property_named_field_disables_field_keyword_mode_for_the_whole_class()
    {
        string code = Emit(WithFieldColumn(), Opts(fieldKeyword: true));

        Assert.DoesNotContain("get => field;", code);
        Assert.Contains("private string _field = null!;", code);
        // Every sibling drops to a backing field too: leaving them on `field` is what raises
        // CS9258 on properties that have nothing to do with the offending column.
        Assert.Contains("private int _id;", code);
        Assert.Contains("get => _name;", code);
    }

    [Fact]
    public void An_escaped_property_named_field_disables_it_too()
    {
        var m = WithFieldColumn();
        m.Properties[^1].Name = "@field";

        Assert.DoesNotContain("get => field;", Emit(m, Opts(fieldKeyword: true)));
    }

    [Fact]
    public void A_class_without_such_a_column_still_uses_the_field_keyword()
        => Assert.Contains("get => field;", Emit(Order(), Opts(fieldKeyword: true)));

    [Fact]
    public void PrivateFieldsAtTop_is_honoured_by_the_field_fallback()
    {
        var o = Opts(fieldKeyword: true);
        o.PrivateFieldsAtTop = true;
        string code = Emit(WithFieldColumn(), o);

        int firstField = code.IndexOf("private int _id;", StringComparison.Ordinal);
        int firstProperty = code.IndexOf("public int Id", StringComparison.Ordinal);
        Assert.True(firstField >= 0 && firstField < firstProperty);
    }

    /// <summary>
    /// Every option must survive the fallback's copy of <see cref="EntityEmitOptions"/>.
    /// </summary>
    /// <remarks>
    /// Driven by reflection rather than by a list of property names, deliberately: the failure this
    /// guards against is a property added to <c>EntityEmitOptions</c> later and not added to the
    /// copy, which would be dropped <em>only</em> for classes that contain a <c>field</c> column —
    /// one file out of a run, no golden baseline moved, nothing to notice. A hand-written list of
    /// today's properties would be exactly as easy to forget to extend as the copy was.
    /// </remarks>
    [Fact]
    public void The_field_keyword_fallback_carries_every_option_through()
    {
        EntityModel model = WithFieldColumn();

        string Render(Action<EntityEmitOptions> mutate)
        {
            var o = new EntityEmitOptions { Namespace = "MyApp.Data", FieldKeyword = true };
            mutate(o);
            return new CSharpEntityEmitter().Emit(model, o);
        }

        string baseline = Render(_ => { });
        var covered = new List<string>();

        foreach (var p in typeof(EntityEmitOptions).GetProperties()
                     .Where(p => p.CanWrite && p.PropertyType == typeof(bool))
                     .Where(p => p.Name != nameof(EntityEmitOptions.FieldKeyword)))
        {
            string flipped = Render(o => p.SetValue(o, !(bool)p.GetValue(o)!));

            Assert.True(flipped != baseline,
                $"EntityEmitOptions.{p.Name} has no effect once the `field` fallback has copied " +
                "the options — it was dropped by the copy.");

            covered.Add(p.Name);
        }

        // The one non-bool property, checked explicitly so the loop above cannot be the whole test.
        Assert.Contains("namespace Other.Ns;", Render(o => o.Namespace = "Other.Ns"));

        // If EntityEmitOptions ever loses all its booleans the loop would pass vacuously.
        Assert.NotEmpty(covered);
    }

    // ---- CS8981: an all-lower-case class name ---------------------------------------
    //
    // --naming-style preserve against a lower_snake_case schema names the class after the table,
    // so an ordinary table yields a type name made only of lower-case ASCII. That is a warning
    // the caller cannot act on without renaming their tables, and an error under
    // TreatWarningsAsErrors, so the generated file states that it accepts the risk.

    [Fact]
    public void All_lower_case_class_name_suppresses_CS8981()
    {
        var m = Order();
        m.ClassName = "orders";
        Assert.Contains("#pragma warning disable CS8981", Emit(m));
    }

    [Theory]
    [InlineData("Order")]        // has an upper-case letter
    [InlineData("order_line")]   // underscore: not all lower-case ASCII
    [InlineData("order2")]       // digit: not all lower-case ASCII
    [InlineData("@event")]       // verbatim identifiers are exempt from CS8981
    public void Class_names_the_diagnostic_does_not_apply_to_carry_no_pragma(string className)
    {
        var m = Order();
        m.ClassName = className;
        Assert.DoesNotContain("#pragma", Emit(m));
    }

    // ---- identifiers that are not identifiers ---------------------------------------

    [Fact]
    public void A_property_name_that_is_only_an_escape_is_refused_not_crashed()
    {
        var m = Order();
        m.Properties[0].Name = "@";

        // Must be a ScaffoldException naming the column (exit 1, "refused"), never an
        // IndexOutOfRangeException from deriving the backing field name (exit 2, "crashed").
        var ex = Assert.Throws<ScaffoldException>(() => Emit(m, Opts(fieldKeyword: false)));
        Assert.Contains("id", ex.Message);
    }
